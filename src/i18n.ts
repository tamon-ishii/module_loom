const orderedFragments = fragments.sort((a, b) => b[0].length - a[0].length);

let locale: UiLocale = "ja";
const sourceText = new WeakMap<Text, string>();
const renderedText = new WeakMap<Text, string>();
const sourceAttributes = new WeakMap<Element, Map<string, string>>();
const renderedAttributes = new WeakMap<Element, Map<string, string>>();
const translatedAttributes = ["title", "placeholder", "aria-label"];

export function currentUiLocale(): UiLocale { return locale; }

export function translateUiText(source: string): string {
  if (locale === "ja" || !/[ぁ-んァ-ン一-龯]/.test(source)) return source;
  const normalized = source.replace(/\s+/g, " ").trim();
  const value = exact[normalized] ?? orderedFragments.reduce((text, [ja, en]) => text.split(ja).join(en), source);
  if (exact[normalized]) {
    const leading = source.match(/^\s*/)?.[0] ?? "";
    const trailing = source.match(/\s*$/)?.[0] ?? "";
    return leading + value + trailing;
  }
  return value.replace(/\b1 items\b/g, "1 item")
    .replace(/\b(\d+) cycle\b/g, (_, count: string) => `${count} ${count === "1" ? "cycle" : "cycles"}`);
}

function translateNode(node: Node): void {
  if (node.nodeType === Node.TEXT_NODE) {
    const text = node as Text;
    if (text.parentElement?.closest("script, style, #cy-container")) return;
    if (text.parentElement?.closest(".tree-label, #ruff-fix-file, #cycle-guide-path")) return;
    if (text.parentElement?.closest("code, pre") && !text.parentElement.closest("#cycle-guide-code-example")) return;
    if (renderedText.get(text) !== text.data) sourceText.set(text, text.data);
    const output = translateUiText(sourceText.get(text) ?? text.data);
    renderedText.set(text, output);
    if (text.data !== output) text.data = output;
    return;
  }
  if (!(node instanceof Element)) return;
  if (node.matches(".tree-label, #ruff-fix-file, #cycle-guide-path")) return;
  for (const attr of translatedAttributes) {
    if (!node.hasAttribute(attr)) continue;
    const source = sourceAttributes.get(node) ?? new Map<string, string>();
    const rendered = renderedAttributes.get(node) ?? new Map<string, string>();
    const current = node.getAttribute(attr) ?? "";
    if (rendered.get(attr) !== current) source.set(attr, current);
    const output = translateUiText(source.get(attr) ?? current);
    sourceAttributes.set(node, source);
    renderedAttributes.set(node, rendered);
    rendered.set(attr, output);
    if (current !== output) node.setAttribute(attr, output);
  }
  for (const child of node.childNodes) translateNode(child);
}

export function setUiLocale(next: UiLocale): void {
  locale = next;
  localStorage.setItem("moduleloom-ui-locale", next);
  document.documentElement.lang = next;
  translateNode(document.body);
}

export function initUiLocale(): UiLocale {
  const saved = localStorage.getItem("moduleloom-ui-locale");
  const initial = saved === "ja" || saved === "en" ? saved
    : (navigator.language || "").toLowerCase().startsWith("ja") ? "ja" : "en";
  setUiLocale(initial);
  const observer = new MutationObserver((changes) => {
    for (const change of changes) {
      if (change.type === "characterData") translateNode(change.target);
      else if (change.type === "attributes") translateNode(change.target);
      else for (const node of change.addedNodes) translateNode(node);
    }
  });
  observer.observe(document.body, { subtree: true, childList: true, characterData: true,
    attributes: true, attributeFilter: translatedAttributes });
  return initial;
}
